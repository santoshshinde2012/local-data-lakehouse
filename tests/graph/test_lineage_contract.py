@pytest.mark.parametrize("name", sorted(queries.TEMPLATES))
def test_lineage_template_has_order_by_and_limit(name):
    q = queries.TEMPLATES[name]
    order = [m.start() for m in re.finditer(r"\bORDER\s+BY\b", q, re.IGNORECASE)]
    limit = [m.start() for m in re.finditer(r"\bLIMIT\b", q, re.IGNORECASE)]
    assert order and limit and order[-1] < limit[-1], f"{name} needs ORDER BY followed by LIMIT"
    assert re.search(r"\bLIMIT\s+\d+\s*$", q.rstrip().splitlines()[-1]), f"{name}: must end with a literal LIMIT"
    assert int(q.rstrip().rsplit(None, 1)[-1]) <= queries.ROW_LIMIT
    assert not re.search(r"\bUNION\b", q, re.IGNORECASE), name
    assert not re.search(r"\b(CREATE|MERGE|DELETE|SET|DROP|ALTER|COPY|CALL)\b", q, re.IGNORECASE), f"{name}: read-only"
    assert not FORBIDDEN.search(q), name
    assert "`Column`" not in q and ":Column" not in q, f"{name}: the label is DataColumn"
    unquoted = re.findall(r"\(\w*:([A-Z][A-Za-z]+)", q)
    assert not unquoted, f"{name}: node labels must be back-quoted ({unquoted})"


