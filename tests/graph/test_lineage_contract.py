def test_pit_status_is_recomputed_from_the_edge_windows(core_build, values):  # noqa: F811
    """The stored pit_status is not taken on trust: the oracle derives it again from the
    DERIVED_FROM / COUNTS_ROWS_OF windows, and range guarantees / parameter consistency from their inputs."""
    derived = {r["feature"]: r for r in values["pit_derivation"]}
    assert list(derived) == list(gspec.GOLD_FEATURES)
    for row in values["pit"]:
        d = derived[row["feature"]]
        assert (d["pit_status"], d["max_upper_vs_as_of_days"], d["reads_after_as_of"]) == \
            (row["pit_status"], row["max_upper_vs_as_of_days"], row["reads_after_as_of"]), row["feature"]
    assert derived["renewals_completed"]["windows"] == ["(-inf, as_of+7)"]
    assert derived["incident_exposed_28d"]["windows"] == ["(as_of-28, as_of]", "unbounded"]
    assert derived["limit_hits_14d"]["reads"] == 4          # COUNT(*) + join key + window bound + the as-of anchor
    t = oracle.load_tables(core_build[0])
    assert oracle.derivation_mismatches(t) == []
    # a stored value that no longer follows from the edges is reported
    gold = spec.column_id(spec.GOLD_TABLE, "renewals_completed")
    t.nodes[gold]["pit_status"] = spec.PIT_COMPLIANT
    t.nodes[spec.column_id(spec.GOLD_TABLE, "active_days_7d")]["range_guarantee"] = "data_dependent"
    t.nodes["param:cap_cut"]["pandas_value"] = 0.8
    found = oracle.derivation_mismatches(t)
    assert len(found) == 3 and "renewals_completed: stored pit_status 'compliant'" in found[0]
    assert "active_days_7d: stored range_guarantee 'data_dependent', recomputed 'window_length(7d)'" in found[1]
    assert "parameter cap_cut: stored consistent True" in found[2]
    # ... and so is an edge window that moved without the stored status following it
    t = oracle.load_tables(core_build[0])
    edge = next(e for e in t.out("COUNTS_ROWS_OF", spec.column_id(spec.GOLD_TABLE, "limit_hits_14d")))
    edge["window"] = "(as_of-14, as_of+3]"
    assert any("limit_hits_14d: stored pit_status 'compliant', recomputed from the edge windows "
               "'undeclared_exception'" in m for m in oracle.derivation_mismatches(t))


