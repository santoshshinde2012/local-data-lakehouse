def test_contract_script_fails_loudly_on_a_bad_build(core_build, tmp_path):  # noqa: F811
    bdir, man = core_build
    missing = run_script("check_lineage_contract.py", "--build", str(tmp_path / "nothing"))
    assert missing.returncode == 1 and "no lineage build" in missing.stderr
    # an unresolved name recorded by the extractor is a contract error, strict or not
    bad = tmp_path / "unresolved"
    shutil.copytree(bdir, bad)
    doc = dict(man, unresolved=[{"where": "Makefile:new-target", "what": "runs scripts/gone.py, which does not exist"}])
    mf.write_json_atomic(bad / spec.LINEAGE_DIR / spec.MANIFEST_FILE, doc)
    p = run_script("check_lineage_contract.py", "--build", str(bad), "--no-ladybug")
    assert p.returncode == 1 and "unresolved name: Makefile:new-target" in p.stdout
    assert json.loads((bad / spec.LINEAGE_DIR / spec.CONTRACT_FILE).read_text())["status"] == "fail"
    # a tampered Parquet table is an integrity error
    tampered = tmp_path / "tampered"
    shutil.copytree(bdir, tampered)
    victim = tampered / spec.LINEAGE_DIR / "edges_DERIVED_FROM.parquet"
    shutil.copy2(tampered / spec.LINEAGE_DIR / "edges_COUNTS_ROWS_OF.parquet", victim)
    p = run_script("check_lineage_contract.py", "--build", str(tampered), "--no-ladybug")
    assert p.returncode == 1 and "changed or missing" in p.stdout
    # --no-ladybug alone only warns (and fails under --strict)
    assert run_script("check_lineage_contract.py", "--build", str(bdir), "--no-ladybug").returncode == 0
    assert run_script("check_lineage_contract.py", "--build", str(bdir), "--no-ladybug", "--strict").returncode == 1


@pytest.mark.parametrize("name", ["case_under_not", "two_cases_take_the_loosest"])
def test_contract_fails_when_a_feature_reads_after_as_of_without_a_declaration(tmp_path, name):
    """A leaky rewrite of the gold SQL (a CASE bound under NOT; a second CASE with a looser bound) must
    fail the contract with a readable reason, and the rest of the contract must still hold on that build."""
    _feature, upper, edits = LEAKY_EDITS[name]
    root = fake_repo(tmp_path)
    (root / spec.GOLD_SQL).write_text(edited_sql(edits))
    bdir = tmp_path / "build"
    _dir, man = lbuild.build_lineage(bdir, "core", repo=root, log=lambda *_: None)
    assert man["unresolved"] == []
    p = run_script("check_lineage_contract.py", "--build", str(bdir))
    assert p.returncode == 1 and "Traceback" not in p.stderr, p.stdout[-2000:] + p.stderr[-2000:]
    fails = [line.strip() for line in p.stdout.splitlines() if "FAIL" in line]
    assert fails == [
        "FAIL  every feature is compliant or a declared exception: undeclared exception (reads after as_of, not "
        "declared in FEATURE_CARDS): ['allowance_used_pct']",
        "FAIL  lineage pit_status = FEATURE_CARDS pit_status for all 22 features: differ: ['allowance_used_pct']"]
    assert "Known conservative cases" in p.stdout and "FEATURE_CARDS; a read that is in fact bounded" in p.stdout
    # everything else still holds on the leaky build: the recomputation agrees, and Cypher = oracle for every
    # answer (two edges to one column with different windows keep a total order)
    assert "ok    stored pit_status, range_guarantee and parameter consistency = recomputed" in p.stdout
    assert "ok    upstream_allowance_used_pct" in p.stdout and "ok    pit: Cypher = oracle" in p.stdout
    with tools.LineageContext(bdir) as ctx:
        data, caveats = tools.lineage_pit(ctx)
        trace, _ = tools.lineage_trace(ctx, GOLD + "allowance_used_pct")
    assert [f["feature"] for f in data["features"]] == ["allowance_used_pct", "first_renewal_after_pricing_change",
                                                        "renewals_completed"]
    assert data["summary"]["undeclared_exception"] == 1
    pricing = sorted(e["window"] for e in trace["edges"] if e["to"] == "silver.churn_pricing_changes.effective_date")
    if upper == 7:
        assert data["features"][0]["max_upper_vs_as_of_days"] == 7 and pricing == ["(-inf, as_of+7)", "(-inf, as_of]"]
        assert any("allowance_used_pct: UNDECLARED exception; its window ends 7 day(s) after as_of "
                   "(silver.churn_pricing_changes.effective_date in (-inf, as_of+7))" in c for c in caveats)
    else:
        assert data["features"][0]["max_upper_vs_as_of_days"] is None and pricing == ["unbounded"]
        assert any("allowance_used_pct: UNDECLARED exception; it has no upper time bound" in c for c in caveats)
        assert any("silver.churn_pricing_changes (effective_date) is read without any time bound" in c
                   for c in caveats)


@pytest.mark.parametrize("name", ["renewals_window_over_all_renewals", "feature_cte_order_by_limit"])
def test_a_stopped_extraction_keeps_the_last_good_lineage(core_build, tmp_path, name):  # noqa: F811
    """The verifier's major finding end to end: a window function in the renewals CTE (and ORDER BY ... LIMIT
    in a feature CTE) no longer yields a compliant graph; the build stops before writing anything, so the
    existing lineage (and its passing contract) stays exactly as it was."""
    message, edits = UNMODELLED_EDITS[name]
    bdir = tmp_path / "build"
    shutil.copytree(core_build[0], bdir)
    before = {p.relative_to(bdir): mf.sha256_file(p) for p in sorted(bdir.rglob("*")) if p.is_file()}
    root = fake_repo(tmp_path)
    (root / spec.GOLD_SQL).write_text(edited_sql(edits))
    with pytest.raises(spec.LineageExtractError, match=message):
        lbuild.build_lineage(bdir, "core", repo=root, log=lambda *_: None)
    assert {p.relative_to(bdir): mf.sha256_file(p) for p in sorted(bdir.rglob("*")) if p.is_file()} == before
    assert not [p.name for p in bdir.iterdir() if p.name.startswith(lbuild.TMP_PREFIX)]


