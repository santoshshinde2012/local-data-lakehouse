    assert p.returncode == 0, p.stdout[-3000:] + p.stderr
    assert "FAIL" not in p.stdout and "WARN" not in p.stdout
    for line in ("all 30 gold SQL output columns resolve", "20 of 22 features compliant",
                 "lineage pit_status = FEATURE_CARDS pit_status for all 22 features",
                 "stored pit_status, range_guarantee and parameter consistency = recomputed from the edge windows",
                 "pit_derivation: Cypher = oracle",
                 "invariant 9: silver.churn_limit_events.hit_at has no gold descendant",
                 "bridge: all 21 business graph types", "Q15_downstream_bronze_hit_at", "Cypher = oracle",
                 "Whole-graph totals (reported, not gated)", "lineage Cypher templates have ORDER BY"):
        assert line in p.stdout, line
    assert "Lineage contract OK (metadata-graph/0.1, profile core" in p.stdout and "; strict" in p.stdout
    doc = json.loads(out.read_text())
